// Clase energética. Escala nueva (A-G, etiqueta desde 2021): «Nueva X». «A-10%» de MHD es una A mejorada.
export const ENERGY_NEW: [string, string][] = [["A", "Nueva A"], ["B", "Nueva B"], ["C", "Nueva C"], ["D", "Nueva D"], ["E", "Nueva E"], ["F", "Nueva F"], ["G", "Nueva G"], ["A-10%", "Nueva A"]];
// Escala anterior (hornos, campanas, cocinas, aire acondicionado, termos…): la letra tal cual. «A+PP» y «A+P» son
// como escribe MHD A+++ y A++.
export const ENERGY_OLD: [string, string][] = [["A+++", "A+++"], ["A++", "A++"], ["A+", "A+"], ["A", "A"], ["B", "B"], ["C", "C"], ["D", "D"], ["E", "E"], ["F", "F"], ["A+PP", "A+++"], ["A+P", "A++"]];

// Excepciones decididas por familia, que mandan sobre la tabla común: en sonido, «Inox» es el acabado plateado de unos
// auriculares o un altavoz; en campanas, «Plata» es acero inoxidable, como el resto de campanas de la tienda.
export const FAMILY_EXCEPTIONS: Record<string, Record<string, string>> = {
  "filtro.color|201,210,215,220,230,240,250,270": { inox: "Plata" },
  "filtro.color|I75": { plata: "Acero inoxidable" },
};
const exceptionsFor = (metafield: string, family: string) => Object.entries(FAMILY_EXCEPTIONS).filter(([where]) => { const [field, families] = where.split("|"); return field === metafield && families.split(",").includes(family); }).reduce((all, [, rows]) => ({ ...all, ...rows }), {} as Record<string, string>);

const key = (text: string) => text.trim().toLowerCase();
const skips = (value: string) => value.trim() === "" || value.trim() === "-";
const several = (source: string) => /[,/]/.test(source);

// Junta la tabla común con la de la familia: manda la común, salvo las filas «no vale» de la familia; las filas que
// solo tiene la familia se quedan; en las de varios colores manda la familia. Devuelve la tabla nueva y las filas cuyo valor cambia.
function merge(rule: FilterRule, common: [string, string][], exceptions: Record<string, string>) {
  const own = new Map(rule.table.map((row) => [key(row.source), row]));
  const commonKeys = new Set(common.map(([source]) => key(source)));
  const changed: { source: string; before: string; after: string }[] = [];
  const table = common.map(([source, value]) => {
    const mine = own.get(key(source));
    if (mine && (skips(mine.value) || several(source))) return mine;
    if (exceptions[key(source)]) return { source, value: exceptions[key(source)] };
    if (mine && mine.value !== value) changed.push({ source, before: mine.value, after: value });
    return { source, value };
  });
  for (const row of rule.table) if (!commonKeys.has(key(row.source))) table.push(row);
  return { table, changed };
}

export function applyCommonTables(profile: FamilyProfile, family = "") {
  const changes: { metafield: string; source: string; before: string; after: string }[] = [];
  const filters = profile.filters.map((rule) => {
    if (rule.method !== "tabla") return rule;
    let common: [string, string][] | null = null;
    if (rule.metafield === "filtro.color") common = COLORS;
    else if (rule.metafield === "features.eficiencia_energ_tica") common = rule.table.some((row) => row.value.startsWith("Nueva")) ? ENERGY_NEW : ENERGY_OLD;
    if (!common) return rule;
    const { table, changed } = merge(rule, common, exceptionsFor(rule.metafield, family));
    changes.push(...changed.map((item) => ({ metafield: rule.metafield, ...item })));
    return { ...rule, table };
  });
  return { profile: { ...profile, filters }, changes };
}

